trSales.list.boolean = { yes: "Evet", no: "Hayır" };

function patch(localePath, sales) {
  const j = JSON.parse(fs.readFileSync(localePath, "utf8"));
  j.crm.sales = sales;
  fs.writeFileSync(
    localePath,
    JSON.stringify(j, null, 2) + "\n",
    "utf8",
  );
}

