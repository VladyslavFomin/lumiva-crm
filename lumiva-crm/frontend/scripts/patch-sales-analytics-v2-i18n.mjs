function patch(langPath, blob) {
  const raw = fs.readFileSync(langPath, 'utf8');
  const j = JSON.parse(raw);
  if (!j.crm?.sales) throw new Error('crm.sales missing in ' + langPath);
  j.crm.sales.analyticsV2 = blob;
  fs.writeFileSync(langPath, JSON.stringify(j, null, 2) + '\n');
}

